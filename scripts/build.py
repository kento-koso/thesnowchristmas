#!/usr/bin/env python3
"""Generate static pages, shared shell, event data and content-based asset versions."""
import argparse
from datetime import date, timedelta
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
PAGES = ('index.html', 'shops.html', 'news.html', 'snowfund.html', 'snowfund-thanks.html')
TOKEN = re.compile(r'{{\s*([\w.]+)\s*}}')

def event_values(config):
    start, last = date.fromisoformat(config['startDate']), date.fromisoformat(config['lastDate'])
    if last < start:
        raise ValueError('lastDate must be on or after startDate')
    if start.year != last.year:
        raise ValueError('Cross-year event requires explicit review of the calendar layout')
    weekdays = '月火水木金土日'
    english_days = ('MON','TUE','WED','THU','FRI','SAT','SUN')
    values = dict(config, year=str(start.year), startLabel=start.strftime('%m.%d'),
                  lastLabel=last.strftime('%m.%d'), calendarStart=start.strftime('%Y%m%d'),
                  calendarEnd=(last + timedelta(days=1)).strftime('%Y%m%d'))
    values.update(startDay=str(start.day), lastDay=str(last.day), month=str(start.month), startWeekday=english_days[start.weekday()], lastWeekday=english_days[last.weekday()], startWeekdayJapanese=weekdays[start.weekday()], lastWeekdayJapanese=weekdays[last.weekday()], monthEnglish=start.strftime('%B'))
    deadline = date.fromisoformat(config['donationCloseDate'])
    values['donationDeadlineLabel'] = f'{deadline.month}月{deadline.day}日'
    values['dateShort'] = f'{start.month}月{start.day}日・{last.day}日'
    values['monthUpper'] = values['monthEnglish'].upper()
    values['dateJapanese'] = f'{start.year}年{start.month}月{start.day}日（{weekdays[start.weekday()]}）・{last.day}日（{weekdays[last.weekday()]}）'
    values['dateWithoutYear'] = values['dateJapanese'].split('年',1)[1]
    values['dateAccessible'] = f'{start.year}年{start.month}月{start.day}日{weekdays[start.weekday()]}曜日・{last.day}日{weekdays[last.weekday()]}曜日'
    return values

def substitute(source, values):
    def replace(match):
        key = match[1]
        if key not in values:
            raise ValueError(f'Unknown template token: {key}')
        return str(values[key])
    return TOKEN.sub(replace, source)

def asset_versions(source, root=ROOT):
    def replace(match):
        attr, quote, value = match.groups()
        parsed = urlsplit(value)
        if parsed.scheme or parsed.netloc or not parsed.path.endswith(('.css', '.js')):
            return match[0]
        path = root / parsed.path.removeprefix('./')
        if not path.is_file():
            raise ValueError(f'Missing asset: {value}')
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
        return f'{attr}={quote}{parsed.path}?v={digest}{quote}'
    return re.sub(r'(src|href)=([\"\'])([^\"\']+)\2', replace, source)

def render(name, source, event):
    for component in ('header', 'footer') + (('garland',) if name == 'index.html' else ()):
        template = (ROOT / 'partials' / f'{component}.html').read_text().rstrip()
        start, end = f'<!-- shared:{component}:start -->', f'<!-- shared:{component}:end -->'
        source, count = re.subn(re.escape(start) + r'.*?' + re.escape(end),
            lambda _: f'{start}\n{template}\n{end}', source, flags=re.S)
        if count != 1:
            raise ValueError(f'{name}: expected one {component} region, found {count}')
    values = {'home': '' if name == 'index.html' else './',
              'top': '#top' if name == 'index.html' else '#page-top'}
    values.update({f'event.{k}': v for k, v in event.items()})
    return asset_versions(substitute(source, values))

def build(check=False):
    event = event_values(json.loads((ROOT / 'config/event.json').read_text()))
    # Serialize rather than concatenate user content into executable JavaScript.
    event_js = '/* Generated by scripts/build.py. Edit config/event.json. */\nwindow.SnowEvent = Object.freeze(' + json.dumps(event, ensure_ascii=False, indent=2) + ');\n'
    changed = []
    js_path = ROOT / 'config/event.js'
    if not js_path.exists() or js_path.read_text() != event_js:
        changed.append('config/event.js')
        if not check:
            js_path.write_text(event_js)
    for name in PAGES:
        result = render(name, (ROOT / 'templates/pages' / name).read_text(), event)
        if not (ROOT / name).exists() or (ROOT / name).read_text() != result:
            changed.append(name)
            if not check:
                (ROOT / name).write_text(result)
    if check and changed:
        raise ValueError('Generated files are stale; run npm run build: ' + ', '.join(changed))
    return changed

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        changed = build(args.check)
        print('Static build: ' + ('all outputs current' if args.check else f'updated {len(changed)} files'))
    except (ValueError, OSError) as error:
        parser.exit(1, str(error) + '\n')
